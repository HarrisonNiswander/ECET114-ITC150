#How to Comment out a Large Block of Code:
    #1 Highlight the code you want to comment out
    #2 Press Ctrl + / (Windows) or Command + / (Mac)

#--------------------------------------------------------------------------------------------

#How to Indent Large Blocks of Code:
    #1 Highlight the code you want to indent
    #2 Press Tab to indent or Shift + Tab to un-indent

